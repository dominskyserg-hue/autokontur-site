  id INTEGER PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  shop_name TEXT,
  phone TEXT,
  working_hours TEXT,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ------------------------------------------------------------
-- МИГРАЦИЯ ДЛЯ ТЕХ, КТО УЖЕ ЗАПУСКАЛ ЭТОТ СКРИПТ РАНЬШЕ
-- ------------------------------------------------------------
ALTER TABLE site_settings ADD COLUMN IF NOT EXISTS shop_name TEXT;

-- Заполняем единственную строку значениями по умолчанию, если её
-- ещё нет — ON CONFLICT DO NOTHING делает эту вставку безопасной
-- для повторного запуска скрипта
INSERT INTO site_settings (id, shop_name, phone, working_hours)
VALUES (1, 'AUTOKONTUR', '+38 (050) 123-45-67', 'Щодня 9:00–19:00')
ON CONFLICT (id) DO NOTHING;

-- Если строка уже существовала (создана до появления shop_name) —
-- проставляем название по умолчанию туда, где оно ещё пустое
UPDATE site_settings SET shop_name = 'AUTOKONTUR' WHERE id = 1 AND shop_name IS NULL;


