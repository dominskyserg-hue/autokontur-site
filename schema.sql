-- ============================================================
-- 9. ТАБЛИЦА site_settings — общие настройки витрины (название
--    магазина, телефон, часы работы), которые показываются в
--    шапке магазина и в самой админ-панели
-- ============================================================
-- Это "синглтон" — в таблице всегда РОВНО одна строка. id жёстко
-- зафиксирован как 1 (PRIMARY KEY + CHECK id = 1), поэтому вставить
-- вторую строку физически невозможно — Postgres сам не даст. Экран
-- "Настройки" в админке всегда читает/обновляет именно эту строку
