-- ------------------------------------------------------------
ALTER TABLE products ADD COLUMN IF NOT EXISTS car_make TEXT;
ALTER TABLE products ADD COLUMN IF NOT EXISTS car_model TEXT;
ALTER TABLE products ADD COLUMN IF NOT EXISTS car_year TEXT;
ALTER TABLE products ADD COLUMN IF NOT EXISTS engine_volume TEXT;
ALTER TABLE products ADD COLUMN IF NOT EXISTS slug TEXT;
ALTER TABLE products ADD COLUMN IF NOT EXISTS meta_title TEXT;
ALTER TABLE products ADD COLUMN IF NOT EXISTS meta_description TEXT;
ALTER TABLE products ADD COLUMN IF NOT EXISTS meta_description_override BOOLEAN NOT NULL DEFAULT false;
ALTER TABLE products ADD COLUMN IF NOT EXISTS image_url TEXT;
ALTER TABLE products ADD COLUMN IF NOT EXISTS image_search_attempted_at TIMESTAMPTZ;


-- ============================================================
-- 5. ИНДЕКСЫ — чтобы поиск оставался быстрым даже при миллионе строк
-- ============================================================

-- Ускоряет поиск/фильтр по марке авто ("покажи всё для Toyota") —
-- именно тот сценарий поиска, ради которого добавлены car_make/car_model
CREATE INDEX IF NOT EXISTS idx_products_car_make ON products (car_make);

-- Составной индекс под "Підбір за автомобілем" (марка + рік + об'єм
-- двигуна разом, см. app/api/products/route.ts и .../car-options/route.ts) —
-- ускоряет и сам поиск подходящих деталей, и получение списков
-- доступных значений для выпадающих списков на витрине
CREATE INDEX IF NOT EXISTS idx_products_car_search ON products (car_make, car_year, engine_volume);

-- Ограничение UNIQUE (supplier_id, article) выше уже само по себе
-- создало индекс — но он "ведущий" по supplier_id, то есть хорошо
-- ускоряет запросы вида "все товары этого поставщика", а вот поиск
-- ПО ОДНОМУ АРТИКУЛУ БЕЗ УКАЗАНИЯ ПОСТАВЩИКА (например, когда сайт
-- ищет товар по артикулу across всех поставщиков сразу) через него
-- быстрым не будет. Поэтому добавляем отдельный индекс именно на
-- article — тогда такой поиск останется мгновенным при любом
-- количестве товаров
CREATE INDEX IF NOT EXISTS idx_products_article ON products (article);

-- Частковий індекс лише на рядки БЕЗ фото — саме такі вибирає фонова
-- черга пошуку фото (app/api/cron/fetch-product-images/route.ts).
-- Частковий (WHERE image_url IS NULL), а не по всій таблиці — бо як
