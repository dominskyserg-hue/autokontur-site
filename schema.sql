  admin_message_id BIGINT PRIMARY KEY,

  -- chat_id покупця, якому потрібно повернути відповідь
  customer_chat_id BIGINT NOT NULL,

  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);


