-- 19. ТАБЛИЦА customer_pricing_rules — персональные скидки/наценки
--     покупателям
-- ============================================================
-- Ручное назначение постоянной скидки ИЛИ наценки конкретному
-- покупателю по номеру телефона (единственный способ идентифицировать
-- покупателя на этом сайте — отдельной таблицы "клиенты"/аккаунтов с
-- паролем нет, см. components/CustomerDashboard.tsx, где вход в
-- "Особистий кабінет" тоже происходит по телефону). Правило
-- применяется автоматически при оформлении заказа
-- (app/api/orders/create/route.ts) — покупателю не нужно вводить
-- промокод, достаточно указать тот же номер телефона, что и раньше.
--
-- rule_type различает направление: 'discount' уменьшает цену, 'markup'
-- увеличивает (например, для покупателей, которым по договорённости
-- считают дороже прайса). У одного телефона одновременно может быть
-- только ОДНО правило — либо скидка, либо наценка, не обе сразу.
--
-- phone хранится в НОРМАЛИЗОВАННОМ виде — последние 9 цифр номера
-- (см. lib/phoneNormalize.ts) — чтобы "+380501234567", "380501234567"
-- и "0501234567" считались ОДНИМ И ТЕМ ЖЕ номером: покупатель мог
-- ввести номер в любом из этих форматов в разные заказы
CREATE TABLE IF NOT EXISTS customer_pricing_rules (
  phone TEXT PRIMARY KEY,

  rule_type TEXT NOT NULL DEFAULT 'discount' CHECK (rule_type IN ('discount', 'markup')),

  -- Для discount практический смысл имеют значения до 100 (проверяется
  -- в app/api/admin/customer-pricing-rules/route.ts), для markup
  -- верхнего предела по смыслу нет — поэтому в самой БД ограничение
  -- только "больше нуля", а не жёсткий CHECK <= 100
  percent NUMERIC(6, 2) NOT NULL CHECK (percent > 0),

  -- Заметка админа — для чего правило ("постоянный клиент", "оптовик",
  -- "наценка за доставку в отдалённый район"). Покупателю не показывается
  note TEXT,

  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);


