-- деталь вручну і передзвонює. Це НЕ замовлення (в orders товар уже
-- обраний і має ціну) — це "лід" на ручний підбір, тому й окрема
-- таблиця, а не запис в orders
CREATE TABLE IF NOT EXISTS vin_requests (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

  -- VIN зберігається як є, без "нормалізації" на кшталт cleanArticle()
  -- у артикулів — це просто довідковий текст для адміністратора, за
  -- ним нічого не шукають і не зіставляють у базі
  vin_code TEXT NOT NULL,

  customer_phone TEXT NOT NULL,

  -- Що саме шукає покупець — вільний текст ("гальмівні колодки
  -- передні", "фара права" тощо)
  description TEXT NOT NULL,

  -- Простий робочий статус для адміністратора: 'new' — ще не
  -- оброблено, 'done' — з покупцем зв'язались і підбір завершено.
  -- Свідомо лише два стани (на відміну від п'яти статусів orders) —
  -- це список заявок на обробку, а не повноцінний конвеєр виконання
  status TEXT NOT NULL DEFAULT 'new' CHECK (status IN ('new', 'done')),

  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_vin_requests_status ON vin_requests (status);


