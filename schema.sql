-- ============================================================
-- ФИНАЛЬНЫЙ SQL-СКРИПТ СОЗДАНИЯ БАЗЫ ДАННЫХ
-- Экран "Поставщики и маппинг Excel" — таблицы поставщиков,
-- их настроек маппинга и товаров.
--
-- Как использовать: откройте Supabase → ваш проект → SQL Editor →
-- New query → вставьте весь этот файл целиком → нажмите "Run".
-- Скрипт безопасно запускать повторно: везде используется
-- IF NOT EXISTS, поэтому повторный запуск не выдаст ошибку и
-- не сломает уже существующие таблицы.
-- ============================================================


-- Включаем расширение pgcrypto — оно даёт функцию gen_random_uuid(),
-- которой мы будем генерировать уникальные ID для строк.
-- В Supabase оно обычно уже включено по умолчанию, но эта строка
-- ничего не сломает, даже если расширение уже есть — просто ничего
-- не сделает (IF NOT EXISTS)
CREATE EXTENSION IF NOT EXISTS pgcrypto;


-- ============================================================
-- 1. ТАБЛИЦА global_exchange_rates — глобальные курсы валют
-- ============================================================
-- Раньше курс валюты хранился в каждом поставщике отдельно (поле
-- suppliers.exchange_rate) — это было неудобно: если курс доллара
-- менялся, приходилось заходить в настройки КАЖДОГО поставщика с
-- долларовым прайсом и поправлять курс вручную. Теперь курс общий
-- для всей валюты: одна строка в этой таблице — один курс, который
-- сразу используется для всех поставщиков, у кого выбрана эта
-- валюта. Поменяли курс здесь один раз — пересчёт сразу применится
-- ко всем таким поставщикам при следующей загрузке прайс-листа.
--
-- Местная валюта (UAH) в этой таблице НЕ хранится — для неё курс
-- всегда считается равным 1.0 прямо в коде, отдельная строка не
-- нужна (искать её здесь и не понадобится)
CREATE TABLE IF NOT EXISTS global_exchange_rates (
  -- Код валюты — три латинские буквы (USD, EUR, RUB...). Он же и
  -- первичный ключ: для каждой валюты в таблице ровно одна строка
  -- с её текущим курсом. Именно на это поле ссылается ON CONFLICT
  -- (currency) DO UPDATE в app/api/rates/route.ts при обновлении
  currency VARCHAR(3) PRIMARY KEY CHECK (currency ~ '^[A-Z]{3}$'),

  -- Текущий курс этой валюты к местной (гривне). NUMERIC — точное
  -- число без ошибок округления, как и все денежные величины в этой
  -- базе (никогда не используем FLOAT для денег). CHECK > 0 —
  -- нулевой или отрицательный курс обнулил бы или сделал
  -- отрицательными вообще все цены, посчитанные по нему
  rate NUMERIC(12, 4) NOT NULL CHECK (rate > 0),

  -- Когда курс в последний раз обновляли — показываем в виджете
  -- курсов в интерфейсе, чтобы админ видел, насколько "свежий"
  -- сейчас курс, и не забывал обновлять его
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);


-- ============================================================
-- 2. ТАБЛИЦА suppliers — поставщики
-- ============================================================
CREATE TABLE IF NOT EXISTS suppliers (
  -- Уникальный ID поставщика. UUID вместо простого числа —
  -- потому что его нельзя угадать перебором (id=1, id=2...) и
  -- он не пересечётся, даже если записи создаются из разных мест.
  -- gen_random_uuid() генерирует новый UUID автоматически при
  -- каждой вставке строки, вручную его указывать не нужно
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

  -- Название компании-поставщика. NOT NULL — то есть обязательно
  -- должно быть заполнено, пустых поставщиков быть не может
  name TEXT NOT NULL,

  -- Контактное лицо — необязательное поле (может остаться пустым)
  contact_name TEXT,

  -- Телефон и email храним в двух отдельных колонках (как и в самой
  -- форме на экране администратора — там это тоже два разных поля),
  -- а не одной общей "phone_email": так удобнее искать, проверять
  -- формат и, например, звонить или писать письма программно
  phone TEXT,
  email TEXT,

  -- Валюта, в которой этот поставщик присылает прайс-лист — код из
  -- 3 латинских букв (UAH, USD, EUR, RUB...). По умолчанию UAH
  -- (местная валюта, украинская гривна) — значит цены из Excel
  -- считаются уже в местной валюте, без пересчёта. Сам курс этой
  -- валюты здесь БОЛЬШЕ НЕ ХРАНИТСЯ (раньше было отдельное поле
  -- exchange_rate прямо на поставщике) — теперь курс общий для всех
  -- поставщиков одной валюты и живёт в таблице global_exchange_rates
  -- выше: так его достаточно поменять один раз в одном месте, а не
  -- у каждого поставщика отдельно
  currency TEXT NOT NULL DEFAULT 'UAH' CHECK (currency ~ '^[A-Z]{3}$'),

  -- Активен ли поставщик прямо сейчас. Поставщика "на паузе" видно
  -- в списке (история и его товары не удаляются), но с ним обычно
  -- временно не работают — например, он поменял прайс или у него
  -- нет товара. По умолчанию новый поставщик сразу активен
  is_active BOOLEAN NOT NULL DEFAULT true,

  -- Когда запись была создана. now() — текущее время сервера базы
  -- данных на момент вставки строки
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

  -- Проверка на уровне базы данных: должен быть указан хотя бы
  -- телефон ИЛИ email (то же самое правило уже есть в форме на
  -- экране, но продублировать его в базе — хорошая привычка:
  -- так некорректная запись не проскочит, даже если её попробуют
  -- создать в обход интерфейса, например через API напрямую)
  CONSTRAINT phone_or_email_required CHECK (phone IS NOT NULL OR email IS NOT NULL)
);

-- ------------------------------------------------------------
-- МИГРАЦИЯ ДЛЯ ТЕХ, КТО УЖЕ ЗАПУСКАЛ ЭТОТ СКРИПТ РАНЬШЕ
-- ------------------------------------------------------------
-- Ровно та же ситуация, что и с order_items ниже: CREATE TABLE
-- IF NOT EXISTS не добавит новые колонки в уже существующую
-- таблицу suppliers (а она у вас уже создана в Supabase). Поэтому
-- отдельно, на всякий случай, добавляем колонку currency через
-- ALTER TABLE — ADD COLUMN IF NOT EXISTS безопасен для повторного
-- запуска
ALTER TABLE suppliers ADD COLUMN IF NOT EXISTS currency TEXT NOT NULL DEFAULT 'UAH' CHECK (currency ~ '^[A-Z]{3}$');
ALTER TABLE suppliers ADD COLUMN IF NOT EXISTS is_active BOOLEAN NOT NULL DEFAULT true;

-- Термін поставки під замовлення — вільний текст ("2-3 дні", "тиждень",
-- "під замовлення з Польщі: 5-7 днів"), а не число: реальні терміни
-- постачальники описують по-різному, і жорсткий формат тут тільки
-- заважав би. Стосується ЛИШЕ товарів БЕЗ наявності (stock = 0) —
-- товар в наявності й так відправляється того ж дня (це вже сказано
-- на вітрині), тому окремо термін для нього не потрібен. NULL —
-- постачальник ще не вказав термін
ALTER TABLE suppliers ADD COLUMN IF NOT EXISTS delivery_time TEXT;

-- Включена ли автоматическая загрузка прайса ЭТОГО поставщика из
-- почты (см. lib/emailPriceImport.ts и app/api/cron/import-supplier-emails).
-- Письма сопоставляются с поставщиком по адресу отправителя = email
-- поставщика (колонка выше), поэтому автозагрузка вообще имеет смысл,
-- только если email заполнен И настроен маппинг колонок Excel. Можно
-- выключить для конкретного поставщика, не трогая остальных — например,
-- если он временно шлёт прайсы вручную по телефону, а не почтой.
-- По умолчанию true — если email указан, автозагрузка сразу пробует
-- работать, отдельно включать её не нужно
ALTER TABLE suppliers ADD COLUMN IF NOT EXISTS email_auto_import_enabled BOOLEAN NOT NULL DEFAULT true;

-- Прямая ссылка на Excel-прайс поставщика (например,
-- "http://postavshik.com/price.xls") — альтернатива автозагрузке по
-- почте (см. email_auto_import_enabled выше) для тех поставщиков, кто
-- просто держит актуальный прайс по одному и тому же адресу, а не
-- присылает его письмом. См. lib/urlPriceImport.ts и
-- app/api/cron/import-supplier-urls. Отдельного переключателя
-- "включено/выключено" для этого способа нет — сам факт, что поле
-- заполнено, уже означает "подхватывать прайс отсюда"; чтобы
-- выключить — достаточно очистить поле. NULL — способ не настроен
ALTER TABLE suppliers ADD COLUMN IF NOT EXISTS price_url TEXT;

-- А колонку exchange_rate, наоборот, теперь УДАЛЯЕМ: курс переехал
-- из поставщика в отдельную таблицу global_exchange_rates (см. выше
-- в этом же файле). DROP COLUMN IF EXISTS безопасен и для тех, у
-- кого этой колонки никогда не было (например, для совсем свежей
-- базы, где вы применяете этот скрипт впервые) — тогда команда
-- просто ничего не сделает
ALTER TABLE suppliers DROP COLUMN IF EXISTS exchange_rate;


-- ============================================================
-- 3. ТАБЛИЦА supplier_excel_mappings — настройки маппинга Excel
-- ============================================================
-- У каждого поставщика ровно ОДНА настройка маппинга (это видно
-- по самому интерфейсу: кнопка "Сохранить настройки поставщика"
-- перезаписывает, а не добавляет новую). Поэтому здесь supplier_id
-- сделан одновременно и первичным ключом (PRIMARY KEY), и внешним
-- ключом (REFERENCES) — это гарантирует связь "один к одному":
-- у поставщика не может быть двух разных настроек маппинга
CREATE TABLE IF NOT EXISTS supplier_excel_mappings (
  -- Ссылка на поставщика. ON DELETE CASCADE означает: если
  -- поставщика удалят, его настройки маппинга удалятся вместе
  -- с ним автоматически — они всё равно бесполезны без поставщика
  supplier_id UUID PRIMARY KEY REFERENCES suppliers(id) ON DELETE CASCADE,

  -- Буква или номер колонки Excel-файла для каждого поля.
  -- Храним как текст ("B", "2" и т.п.), потому что именно так их
  -- вводит пользователь в интерфейсе — не обязательно преобразовывать
  -- сразу в число, это делает уже серверный код при разборе файла.
  -- Артикул и цена обязательны для работы маппинга, поэтому NOT NULL
  article_column TEXT NOT NULL,
  brand_column TEXT,
  name_column TEXT,
  price_column TEXT NOT NULL,
  stock_column TEXT,

  -- Колонки с маркой и моделью автомобиля, для которого подходит
  -- деталь (например, "Toyota" / "Camry") — если поставщик присылает
  -- такие колонки в своём прайсе. Нужны для SEO-наполнения карточек
  -- товара (см. products.car_make/car_model ниже): чтобы деталь можно
  -- было найти по запросу вида "втулка стабилизатора на тойоту".
  -- Необязательные — если поставщик не указывает авто, эти колонки
  -- просто не заполняются, и товар сохраняется без марки/модели
  car_make_column TEXT,
  car_model_column TEXT,

  -- Колонки с годом выпуска и объёмом двигателя авто, для которого
  -- подходит деталь (например, "2008" / "2.0") — как и марка/модель
  -- выше, нужны только для поиска покупателем "Підбір за автомобілем"
  -- на витрине (см. products.car_year/engine_volume ниже) и точно так
  -- же необязательны: не у каждого поставщика в прайсе есть такие колонки
  car_year_column TEXT,
  engine_volume_column TEXT,

  -- Колонка со ссылкой на фото товара (например, "H") — если
  -- поставщик присылает прямые ссылки на фотографии в своём
  -- прайс-листе. Необязательная: не у каждого поставщика такая
  -- колонка есть — тогда фото по-прежнему ищется автоматически (см.
  -- lib/productImagePipeline.ts и app/api/cron/fetch-product-images/
  -- route.ts). Если колонка указана, ссылка из неё считается более
  -- надёжной, чем найденная автопоиском, и подставляется в
  -- products.image_url при каждой загрузке прайса (см. upsertBatch
  -- в app/api/suppliers/parse-excel/route.ts)
  image_column TEXT,

  -- С какой строки файла начинаются данные (пропускаем строки-шапки)
  start_row INTEGER NOT NULL DEFAULT 1,

  -- Наценка в процентах. NUMERIC(6,2) — до 9999,99% с двумя знаками
  -- после запятой, этого более чем достаточно для процента наценки
  markup_percent NUMERIC(6, 2) NOT NULL DEFAULT 0,

  -- Когда настройки в последний раз сохраняли/меняли
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ------------------------------------------------------------
-- МИГРАЦИЯ ДЛЯ ТЕХ, КТО УЖЕ ЗАПУСКАЛ ЭТОТ СКРИПТ РАНЬШЕ
-- ------------------------------------------------------------
ALTER TABLE supplier_excel_mappings ADD COLUMN IF NOT EXISTS car_make_column TEXT;
ALTER TABLE supplier_excel_mappings ADD COLUMN IF NOT EXISTS car_model_column TEXT;
ALTER TABLE supplier_excel_mappings ADD COLUMN IF NOT EXISTS car_year_column TEXT;
ALTER TABLE supplier_excel_mappings ADD COLUMN IF NOT EXISTS engine_volume_column TEXT;
ALTER TABLE supplier_excel_mappings ADD COLUMN IF NOT EXISTS image_column TEXT;


-- ============================================================
-- 3.1 ТАБЛИЦА supplier_markup_rules — правила наценки/скидки
--     по фильтру (бренд / категория / диапазон цены поставщика)
-- ============================================================
-- Раньше у поставщика была ровно ОДНА наценка на ВСЕ его товары
-- (supplier_excel_mappings.markup_percent выше). Этого не хватает,
-- когда нужно, например, поставить на дорогие детали Bosch наценку
-- поменьше, а на дешёвый неоригинал — побольше. Здесь у поставщика
-- может быть НЕСКОЛЬКО таких правил — при загрузке прайса каждый
-- товар проверяется по ним ПО ПОРЯДКУ СОЗДАНИЯ (created_at), и
-- применяется markup_percent/discount_percent ПЕРВОГО подошедшего
-- правила. Если ни одно правило не подошло (или правил нет вовсе) —
-- используется обычная наценка поставщика, как и раньше (см.
-- app/api/suppliers/parse-excel/route.ts)
CREATE TABLE IF NOT EXISTS supplier_markup_rules (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

  -- Поставщик, которому принадлежит правило. ON DELETE CASCADE — при
  -- удалении поставщика все его правила наценки удаляются вместе с ним
  supplier_id UUID NOT NULL REFERENCES suppliers(id) ON DELETE CASCADE,

  -- Все условия ниже — НЕОБЯЗАТЕЛЬНЫЕ (NULL = "любой"). Правило без
  -- ни одного условия подходит вообще всем товарам поставщика — это
  -- осознанно допустимо (действует как обычная наценка, только со
  -- скидкой в придачу)
  brand TEXT,
  category_slug TEXT,

  -- Диапазон цены ПОСТАВЩИКА (products.cost_price, уже в местной
  -- валюте после пересчёта по курсу) — НЕ розничной цены с наценкой:
  -- иначе для расчёта наценки понадобилась бы уже посчитанная наценка,
  -- получился бы замкнутый круг
  price_from NUMERIC(12, 2),
  price_to NUMERIC(12, 2),

  -- Скидка для покупателя ПОВЕРХ уже готовой (с наценкой) цены —
  -- см. products.discount_percent ниже. Например, наценка 20% и
  -- скидка 8% на дорогие детали Bosch означают: розничная цена
  -- считается с наценкой 20%, а затем покупателю показывается такая
  -- цена со скидкой 8% (и старая цена — зачёркнутой)
  discount_percent NUMERIC(6, 2) NOT NULL DEFAULT 0,
  markup_percent NUMERIC(6, 2) NOT NULL DEFAULT 0,

  -- Выключенное правило (is_active = false) сохраняется в списке, но
  -- не применяется при загрузке прайса — так можно временно отключить
  -- правило, не удаляя и не теряя его настройки
  is_active BOOLEAN NOT NULL DEFAULT true,

  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Ускоряет "все правила этого поставщика, по порядку создания" —
-- именно так их выбирает app/api/suppliers/parse-excel/route.ts
CREATE INDEX IF NOT EXISTS idx_supplier_markup_rules_supplier
  ON supplier_markup_rules (supplier_id, created_at);


-- ============================================================
-- 4. ТАБЛИЦА products — товары, загруженные из прайс-листов
-- ============================================================
CREATE TABLE IF NOT EXISTS products (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

  -- Товар всегда принадлежит конкретному поставщику. ON DELETE
  -- CASCADE — если поставщика удаляют, весь его каталог товаров
  -- удаляется вместе с ним (в этом проекте товары существуют
  -- только благодаря прайс-листу поставщика, отдельно от него
  -- они не имеют смысла). Если захотите вместо этого получать
  -- ошибку при удалении поставщика с товарами "для подстраховки" —
  -- замените CASCADE на RESTRICT
  supplier_id UUID NOT NULL REFERENCES suppliers(id) ON DELETE CASCADE,

  -- Очищенный артикул (уже без пробелов/дефисов/спецсимволов,
  -- в верхнем регистре — этим занимается функция cleanArticle()
  -- в серверном коде до того, как строка попадёт сюда)
  article TEXT NOT NULL,

  brand TEXT,
  name TEXT,

  -- ---- SEO-наполнение карточки товара ----
  -- Марка и модель автомобиля, для которого подходит деталь (Toyota /
  -- Camry) — заполняются из Excel-прайса, если у поставщика есть
  -- такие колонки (см. supplier_excel_mappings.car_make_column выше).
  -- Без этих полей запрос вида "втулка стабилизатора на тойоту"
  -- физически не с чем сопоставить — название детали само по себе
  -- обычно не содержит марку авто
  car_make TEXT,
  car_model TEXT,

  -- Год выпуска и объём двигателя авто, для которого подходит деталь
  -- (например, "2008" / "2.0") — заполняются точно так же, из
  -- Excel-прайса, если у поставщика есть такие колонки (см.
  -- supplier_excel_mappings.car_year_column/engine_volume_column
  -- выше). Используются экраном "Підбір за автомобілем" на витрине
  -- (components/StorefrontHome.tsx): покупатель выбирает марку, рік
  -- і об'єм двигуна — и бэкенд ищет підходящі деталі по цим трьом
  -- колонкам разом (см. app/api/products/route.ts). Текст, а не число —
  -- потому что в прайсах год иногда указан диапазоном ("2005-2010"),
  -- а объём — с дробной частью или обозначением топлива ("2.0 TDI")
  car_year TEXT,
  engine_volume TEXT,

  -- ЧПУ-адрес страницы товара (например "vtulka-stabilizatora-
  -- toyota-camry-ab123") и мета-теги для поисковиков. Генерируются
  -- автоматически при загрузке прайса из названия/бренда/марки/
  -- модели/артикула (см. app/api/suppliers/parse-excel/route.ts) —
  -- вручную их заполнять для каждого из тысяч товаров нереально.
  -- meta_description можно точечно переписать вручную для важных
  -- товаров через экран "Товары" — тогда авто-генерация её больше
  -- не перезаписывает при повторной загрузке прайса.
  --
  -- slug специально БЕЗ UNIQUE: он собирается из данных, которые
  -- могут совпасть у двух разных поставщиков (одинаковый артикул и
  -- бренд, но без указанной модели авто) — а сама загрузка прайса
  -- не должна падать из-за случайного совпадения строки в адресе
  slug TEXT,
  meta_title TEXT,
  meta_description TEXT,

  -- true — если meta_description правили вручную на экране "Товары".
  -- Пока этот флаг true, автогенерация при повторной загрузке
  -- прайса НЕ перезаписывает meta_description этого товара — иначе
  -- вручную доработанное SEO-описание терялось бы при каждом
  -- обновлении прайс-листа поставщика
  meta_description_override BOOLEAN NOT NULL DEFAULT false,

  -- Фото товара — либо настоящая ссылка на картинку (вставлена
  -- вручную на экране "Товары"), либо data:-URI с картинкой,
  -- загруженной файлом прямо с компьютера админа (тогда сама
  -- картинка хранится base64-строкой прямо в этой колонке —
  -- отдельное файловое хранилище для этого не заводили).
  -- НЕ трогается при загрузке прайс-листа — в отличие от
  -- meta_description, фото не нужно генерировать автоматически
  -- при каждом импорте, поэтому и флаг "override" ему не нужен
  image_url TEXT,

  -- Когда в последний раз ПЫТАЛИСЬ найти фото автоматически (см.
  -- app/api/cron/fetch-product-images/route.ts и lib/productImagePipeline.ts) —
  -- независимо от того, нашли фото или нет. Нужно, чтобы фоновая
  -- очередь не пыталась искать фото для одного и того же товара на
  -- каждом запуске подряд: если попытка была неудачной, товар не
  -- берётся в очередь повторно ближайшие несколько дней (см.
  -- RETRY_AFTER_DAYS в коде роута)
  image_search_attempted_at TIMESTAMPTZ,

  -- Оптовая цена поставщика (столбец называется cost_price, как
  -- вы и просили). NUMERIC(12,2) — до 9 999 999 999,99, с точностью
  -- до копейки; для денег всегда используем NUMERIC, а не FLOAT,
  -- потому что FLOAT округляет и может незаметно "потерять" копейки
  cost_price NUMERIC(12, 2) NOT NULL DEFAULT 0,

  -- Розничная цена — уже посчитанная (опт + наценка, а если по
  -- товару сработало правило наценки со скидкой — то ещё и скидка
  -- уже вычтена, см. supplier_markup_rules выше), та цена, которую
  -- реально платит покупатель на сайте
  retail_price NUMERIC(12, 2) NOT NULL DEFAULT 0,

  -- Скидка (%), применённая к этому товару правилом наценки
  -- поставщика (supplier_markup_rules.discount_percent) — ЧИСТО ДЛЯ
  -- ОТОБРАЖЕНИЯ на витрине (старая цена зачёркнута + "-8%"), в
  -- retail_price выше скидка уже учтена. 0 — скидки нет, обычная цена
  discount_percent NUMERIC(6, 2) NOT NULL DEFAULT 0,

  stock INTEGER NOT NULL DEFAULT 0,

  -- false — товар СКРЫТ с витрины: страница товара отдаёт 404,
  -- не участвует в поиске, категориях, /marky и sitemap.xml. Тот же
  -- принцип, что и suppliers.is_active выше — товар при этом НЕ
  -- удаляется из базы (заказы/кросс-номера/аналитика продолжают на
  -- него ссылаться). Используется для явно тестовых/мусорных записей
  -- (напр. поставщик "Тестовий постачальник" — товары TEST0001-30,
  -- ARTSEO1-3 — или строк-артефактов импорта вроде article='0')
  is_active BOOLEAN NOT NULL DEFAULT true,

  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),

  -- ГЛАВНОЕ: составной уникальный ключ "Артикул + Поставщик".
  -- Именно на него ссылается "ON CONFLICT (supplier_id, article)"
  -- в серверном коде — без этого ограничения Upsert работать не
  -- будет (Postgres не поймёт, какую строку считать "той же самой"
  -- при повторной загрузке прайс-листа)
  UNIQUE (supplier_id, article)
);

