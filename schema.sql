-- Частковий (WHERE image_url IS NULL), а не по всій таблиці — бо як
-- тільки товар отримає фото, він назавжди випадає з цієї вибірки, і
-- індексувати рядки, які туди ніколи більше не потраплять, немає сенсу
CREATE INDEX IF NOT EXISTS idx_products_missing_image
  ON products (image_search_attempted_at)
  WHERE image_url IS NULL;


-- ============================================================
-- 5.1. ТАБЛИЦА product_images — ДОДАТКОВІ фото товару (галерея)
-- ============================================================
-- products.image_url лишається ГОЛОВНИМ фото товару (як і раніше —
-- саме воно показується в списках, пошуку, Open Graph). Ця таблиця —
-- лише ДОДАТКОВІ фото для галереї на картці товару: у товару може
-- бути 0 і більше рядків тут. Окрема таблиця, а не масив у колонці
-- products, бо кожне фото має власний підпис (label) і порядок
-- показу (sort_order), а такими даними рядок в одній комірці не
-- буде — це вже "багато до одного", класичний випадок для окремої
-- таблиці з FOREIGN KEY
CREATE TABLE IF NOT EXISTS product_images (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

  -- ON DELETE CASCADE — видалили товар, його додаткові фото більше
  -- нікому не потрібні, видаляються разом з ним автоматично
  product_id UUID NOT NULL REFERENCES products(id) ON DELETE CASCADE,

  -- Посилання на файл у Vercel Blob (якщо фото завантажили файлом з
  -- комп'ютера, lib/imageStorage.ts) або звичайне http(s)-посилання
  -- (якщо адмін вставив чуже фото вручну) — той самий принцип, що і
  -- в products.image_url
  image_url TEXT NOT NULL,

  -- Короткий підпис "що саме на цьому фото" (наприклад "упаковка",
  -- "загальний вигляд", "маркування") — з нього формується унікальний
  -- alt для картинки: "БРЕНД АРТИКУЛ — label". NULL, якщо адмін ще
  -- не заповнив підпис — тоді alt підставляє порядковий номер фото,
  -- аби не показувати однаковий alt на кількох фото одразу
  label TEXT,

  -- Порядок показу в галереї (0 — перше додаткове фото після
  -- головного). Просте ціле число, а не зв'язаний список чи дата
  -- створення — адміну простіше міняти місцями два фото, ніж
  -- переставляти дати
  sort_order INTEGER NOT NULL DEFAULT 0,

  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Ускоряет "дай усі додаткові фото цього товару за порядком показу" —
-- саме так вибирає їх картка товару (lib/productDetail.ts)
CREATE INDEX IF NOT EXISTS idx_product_images_product_id ON product_images (product_id, sort_order);


