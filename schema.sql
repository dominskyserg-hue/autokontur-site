-- 12. ТАБЛИЦА vin_requests — заявки "Підбір за VIN"
-- ============================================================
-- Блок "Підбір за VIN" на витрині (components/StorefrontHome.tsx) —
-- для покупців, які не змогли знайти деталь за артикулом. Замість
-- пошуку по каталогу вони просто лишають заявку: VIN-код автомобіля,
