// Общие части подкатегорий датчиков: видны блоком "Підкатегорії" на
// странице "Датчики", в общую сетку каталога не выводятся; в подкатегории
// остаются только товары, которые уже есть в "Датчики"
const SENSOR_SUB = {
  parentCategorySlug: 'datchyky',
  hideFromIndex: true,
  onlyWithinParent: true,
  allowSensors: true,
} as const;

function sensorSub(slug: string, name: string, what: string, matchGroups: string[][], excludeWords?: string[]): Stage3CategoryDef {
  return {
    ...SENSOR_SUB,
    insertAfter: 'datchyky',
    slug,
    name,
    h1: `${name} — купити з доставкою по Україні`,
    metaTitle: `${name} купити — оригінал і аналоги | DominatorParts`,
    metaDescription: `${name} для іномарок в наявності: оригінал та перевірені аналоги. Доставка по всій Україні.`,
    intro: `${what} Підберіть потрібний за артикулом або маркою авто.`,
    matchGroups,
    excludeWords,
  };
}

