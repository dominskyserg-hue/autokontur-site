// Все корни одним списком — для SQL (поиск по name_search). Слова правил
// проходят ту же замену латинских двойников, что и name_search
// (lib/latinLookalikes.ts), — иначе латинское слово правила ("common rail")
// не совпало бы с уже заменённым названием
function likeArray(words: string[]): string[] {
  return words.map((w) => `%${foldLookalikes(w)}%`);
}

// SQL-условие одного правила + его параметры (нумерация с startIndex)
export function buildExtraRuleCondition(rule: ExtraCategoryRule, startIndex: number): { sql: string; params: unknown[] } {
  const params: unknown[] = [];
  const parts: string[] = [
    // Как в основных правилах: название, начинающееся с "пыльник", никуда не попадает
    "p.name_search !~* '^[[:space:]]*([A-Za-zА-Яа-яІіЇїЄєҐґ]?[0-9]+/)*[[:space:]]*(пыльник|пильник|пильовик)'",
  ];
  // Сам товар — датчик ("Датчик давления ГУР", "Сенсор рівня палива") — не
  // сюда. "Ступица с датчиком ABS", "Клипса датчика" — это не датчики, их пропускаем
  if (!rule.allowSensors) parts.push("p.name_search !~* '^[[:space:]]*(датчик|сенсор)'");
  for (const group of rule.all) {
    params.push(likeArray(group));
    parts.push(`p.name_search ILIKE ANY($${startIndex + params.length - 1}::text[])`);
  }
  if (rule.exclude && rule.exclude.length > 0) {
    params.push(likeArray(rule.exclude));
    parts.push(`NOT (p.name_search ILIKE ANY($${startIndex + params.length - 1}::text[]))`);
  }
  return { sql: parts.join(' AND '), params };
}
