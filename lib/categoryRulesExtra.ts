// Основные правила категорий — в lib/categories.ts (matchGroups). Они
// узкие: например, "Кермове управління" знала только украинское
// "рульов", а "Ремені та ролики" требовали слово "ГРМ". Здесь —
// дополнительные правила для товаров, которые под основные не попали.
//
// КАК РАБОТАЕТ:
//   - применяются ТОЛЬКО к товарам, у которых нет ни одной категории по
//     основным правилам. Поэтому товар, у которого категория уже есть,
//     её не меняет — только товары "без категории" получают категорию;
//   - товару достаётся ОДНА категория — первого подходящего правила;
//   - сравнение — по products.name_search (название в нижнем регистре,
//     латинские буквы-двойники заменены кириллицей: "фiльтр" → "фільтр");
//   - как и в основных правилах, названия, которые НАЧИНАЮТСЯ с
//     "пыльник/пильник/пильовик", никуда не попадают (решение владельца).
//
// ПОРЯДОК = ПРИОРИТЕТ (сверху вниз, первое совпадение побеждает):
//   конкретные сочетания слов стоят выше общих. Например:
//   - фильтры (салонный → масляный → воздушный) — самые однозначные, первыми;
//     салонный раньше воздушного: "Фільтр повітряний салону" — салонный;
//   - рулевое (в т.ч. "шланг ГУР", "насос ГУР") — раньше охлаждения, иначе
//     "помпа ГУР" ушла бы в охлаждение по слову "помп";
//   - опоры двигателя/КПП (Кріплення) — раньше трансмиссии, иначе
//     "подушка КПП" ушла бы в трансмиссию по слову "кпп";
//   - охлаждение исключает кондиционер/печку — те идут в "Опалення і клімат".
//
// В ЭТОТ ЭТАП — только однозначные сочетания. Общие слова (ролик, ремень,
// болт, рычаг, клапан, шланг, насос, втулка, подшипник, крышка) — только
// вместе с уточнением ("насос водяной", "втулка стабилизатора",
// "рычаг передний").
//
// Ремни (решение владельца): раздел "Ремені та ролики" (remeni-rolyky-grm)
// с подкатегориями "Ремені та ролики ГРМ" (remeni-rolyky-grm-komplekty) и
// "Поліклинові ремені та ролики" (polyklynovi-remeni-rolyky). Товар
// подкатегории автоматически попадает и в раздел (lib/categoryAssignment.ts).
// Ролики/натягувачи без уточнения, к какому приводу, — только в раздел.
// ============================================================

