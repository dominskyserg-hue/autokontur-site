// Англійські позначки сторони — трапляються ЗАМІСТЬ російських у
// частини постачальників ("Prado 120 rear"). Регулярний вираз з
// межами слова (\b), щоб не зачепити "rear" всередині якогось іншого
// слова чи артикула
const ENGLISH_SIDE_WORDS: Readonly<Record<string, string>> = {
  rear: 'задній',
  front: 'передній',
  left: 'лівий',
  right: 'правий',
};

// Перекладає ОДНЕ кириличне слово за словником вище, зберігаючи
// регістр першої літери оригіналу (щоб "Передний" -> "Передній", а
// не "передній" в середині речення з великої літери). null — слова
// немає в словнику, воно нерозпізнане
function translateRussianWord(word: string): string | null {
  const lower = word.toLowerCase();
  const translated = RUSSIAN_TO_UKRAINIAN_WORDS[lower];
  if (translated === undefined) return null;

  const firstChar = word.charAt(0);
  if (firstChar && firstChar === firstChar.toUpperCase() && firstChar !== firstChar.toLowerCase()) {
    return translated.charAt(0).toUpperCase() + translated.slice(1);
  }
  return translated;
}

// Символи, яких немає в українській абетці, але є в російській —
// якщо після перекладу словником в рядку лишився такий символ, отже
// лишилось якесь нерозпізнане російське слово (можливо, злите з
// іншим текстом чи з незвичною формою), і довіряти результату не
// можна
const NON_UKRAINIAN_CYRILLIC_RE = /[ыэъё]/i;

// Кириличне "слово" — послідовність літер української/російської
// абетки (обидві настільки перетинаються, що простіше матчити разом,
// а відрізняти "чужі" літери окремою перевіркою вище)
const CYRILLIC_WORD_RE = /[а-яёіїєґ]+/gi;

/**
 * Очищує/перекладає сире значення products.car_model перед показом
 * покупцю у застосовності товару. Дивись коментар на початку файлу
 * щодо семантики значення, що повертається (null / '' / рядок).
 */
export function cleanApplicability(rawModel: string | null | undefined): string | null {
  let trimmed = (rawModel ?? '').trim();
  if (!trimmed) return '';

  // Сирі TecDoc-коди на кшталт "#T17#, #E10#" — Крок 1 аналізу
  // показав, що надійно розшифрувати їх неможливо (див. коментар на
  // початку файлу), тому просто не показуємо застосовність
  if (trimmed.includes('#')) return null;

  // " > " — роздільник рівнів в офіційному записі TecDoc car_model
  // (напр. "TESLA > MODEL Y > MODEL Y (5YJY) [03/2019 ->]") —
  // покупцю показувати сирий ">" не варто. Прибираємо ЛИШЕ варіант із
  // пробілом з ОБОХ боків (" > ") і кінцевий " >" — компактний запис
  // без пробілів ("->", "15->", "06->") це вже інша річ, "з якого
  // року" в позначенні постачальника, її свідомо НЕ чіпаємо (як і в
  // products.name, див. lib/productNameCleanup.ts)
  trimmed = trimmed
    .replace(/ > /g, ' ')
    .replace(/ >$/, '')
    .replace(/\s+/g, ' ')
    .trim();

  // СПЕРШУ кириличні слова — перекладаємо за словником; якщо бодай
  // одне слово в словнику не знайшлось, весь рядок вважається
  // ненадійним (hasUnknownWord) і застосовність показана не буде.
  // ВАЖЛИВО: англійські rear/front/left/right перекладаються ПІСЛЯ
  // цього кроку, а не до нього — інакше вже перекладене українське
  // слово "задній" (містить літеру "і") саме потрапило б під
  // CYRILLIC_WORD_RE як "нерозпізнане кириличне слово" (адже
  // словник RUSSIAN_TO_UKRAINIAN_WORDS має ключем російське
  // "задний", а не вже перекладене українське "задній") і зламало б
  // результат
  let hasUnknownWord = false;
  let result = trimmed.replace(CYRILLIC_WORD_RE, (word) => {
    const translated = translateRussianWord(word);
    if (translated === null) {
      hasUnknownWord = true;
      return word;
    }
    return translated;
  });

  if (hasUnknownWord) return null;
  if (NON_UKRAINIAN_CYRILLIC_RE.test(result)) return null;

  // ПІСЛЯ кириличного перекладу — англійські позначки сторони
  // (той самий принцип, що й раніше, для постачальників, які пишуть
  // "rear"/"front" замість "задний"/"передний")
  result = result.replace(/\b(rear|front|left|right)\b/gi, (match) => {
    const translated = ENGLISH_SIDE_WORDS[match.toLowerCase()];
    if (match.charAt(0) === match.charAt(0).toUpperCase()) {
      return translated.charAt(0).toUpperCase() + translated.slice(1);
    }
    return translated;
  });

  // Подвійні пробіли (частий "хвіст" з Excel-прайсів постачальників)
  return result.replace(/\s+/g, ' ').trim();
}
