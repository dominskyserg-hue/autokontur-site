// ============================================================
// Ссылка на фото товара для ВЫВОДА (сайт, API витрины, микроразметка).
//
// Фото поставщиков показываются прямо с их серверов, и часть ссылок в
// прайсах — http:// (SI1IV: http://i.syndicar.com.ua/...). На https-сайте
// браузер сам переводит такие картинки на https, но Google в микроразметке
// и строгие браузеры видят "небезопасное содержимое". Поэтому при выводе
// меняем http:// на https:// (сервер поставщика отвечает по https —
// проверено выборкой 29.09.2026). В базе ссылка остаётся как в прайсе
// ============================================================

export function publicImageUrl(url: string | null | undefined): string | null {
  if (!url) return null;
  return url.replace(/^http:\/\//i, 'https://');
}
