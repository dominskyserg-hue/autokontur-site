// ============================================================
// Выключатель Особистого кабінету покупця.
//
// Кабинет ВРЕМЕННО ВЫКЛЮЧЕН по итогам аудита безопасности: "вход" в
// него — просто ввод номера телефона без SMS-кода, поэтому любой мог
// ввести чужой номер и увидеть чужие заказы, адреса, VIN, а через
// cookie customer_phone — ещё и персональные цены (считаются от
// закупочной). Код кабинета и данные в базе НЕ удалены — понадобятся,
// когда появится вход по одноразовому коду.
//
// Включить обратно: переменная окружения CUSTOMER_CABINET_ENABLED=true
// (Vercel → Settings → Environment Variables) и Redeploy. Переменной
// нет или любое другое значение — кабинет выключен.
//
// Где действует:
//   - middleware.ts — все /api/customer/* отвечают 403 (одна проверка);
//   - lib/customerPricing.ts — персональные цены по cookie не применяются;
//   - шапка/витрина/избранное — ссылки "Кабінет" скрыты;
//   - app/account — вместо кабинета показывается текст ниже.
//
// Клиентские компоненты не видят обычные переменные окружения, поэтому
// next.config.mjs пробрасывает то же значение в браузер как
// NEXT_PUBLIC_CUSTOMER_CABINET_ENABLED (подставляется при сборке —
// после смены переменной нужен Redeploy)
// ============================================================

export function isCustomerCabinetEnabled(): boolean {
  return (
    process.env.CUSTOMER_CABINET_ENABLED === 'true' ||
    process.env.NEXT_PUBLIC_CUSTOMER_CABINET_ENABLED === 'true'
  );
}

// Текст для покупателя — один и тот же в ответе API (403) и на странице /account
export const CUSTOMER_CABINET_DISABLED_MESSAGE =
  'Особистий кабінет тимчасово недоступний. Статус замовлення можна дізнатися в Telegram-боті або за телефоном.';
