// Нормализация номера телефона к единому ключу — последние 9 цифр
// (значащая часть украинского мобильного номера без кода страны и
// ведущего нуля). Нужна, чтобы одного и того же покупателя узнавать
// независимо от того, в каком формате он ввёл номер в разных заказах:
// "+380501234567", "380501234567" и "0501234567" — все три дают
// один и тот же ключ "501234567".
//
// Используется для персональных скидок (customer_discounts,
// app/api/orders/create/route.ts, app/api/admin/customer-discounts/*) —
// единственное место в проекте, где нужно НАДЁЖНО узнать "это тот же
// человек, что и раньше". Для остального (поиск заказов по телефону
// в админке и т.п.) применяется обычный ILIKE по подстроке — там
// ложные не-совпадения не критичны, а тут критичны: иначе скидка
// просто не сработает
// ============================================================
export function normalizePhone(raw: string): string {
  const digits = raw.replace(/\D/g, '');
  return digits.slice(-9);
}
