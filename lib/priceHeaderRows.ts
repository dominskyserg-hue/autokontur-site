// Если в настройках поставщика разбор начинается с 1-й строки, а в файле
// там шапка таблицы, шапка импортировалась как товар: артикул "НОМЕР",
// "КОД", "АРТИКУЛ", "CATITEMNO", название "Наименование", бренд "Бренд"
// (так было у SI1IV, Libron, A1R, AVN1, AVTH1, D1M, HL1K, AVDOC).
// Импорт (lib/priceListImport.ts) пропускает строку, если её артикул —
// типичный заголовок колонки из этого списка.
//
// Ключи — в том же виде, что артикул после cleanArticle(): верхний регистр,
// без пробелов и знаков, из кириллицы остаются только А-Я — поэтому
// украинские І/Ї/Є выпадают ("Ціна" -> "ЦНА", "Кількість" -> "КЛЬКСТЬ",
// "Індекс" -> "НДЕКС"). Только слова-заголовки: настоящий артикул детали
// почти всегда содержит цифры
// ============================================================

export const HEADER_ARTICLE_KEYS: ReadonlySet<string> = new Set([
  // артикул / номер
  'НОМЕР', 'КОД', 'КОДТОВАРА', 'КОДТОВАРУ', 'АРТИКУЛ', 'АРТ', 'АРТИКУЛПРОИЗВОДИТЕЛЯ', 'АРТИКУЛВИРОБНИКА',
  'КАТАЛОЖНЫЙНОМЕР', 'КАТАЛОЖНЫЙНОМЕРПРОИЗВОДИТЕЛЯ', 'КАТАЛОЖНИЙНОМЕР', 'НОМЕРДЕТАЛИ', 'НОМЕРДЕТАЛ',
  'НОМЕРЗАПЧАСТИ', 'НОМЕРЗАПЧАСТИНИ', 'ИНДЕКС', 'НДЕКС', 'НДЕКСНТ', 'ARTICLE', 'ARTICLENUMBER', 'ARTNO', 'ARTNR',
  'SKU', 'PARTNUMBER', 'PARTNO', 'CATALOGNUMBER', 'CATALOGNO', 'CATITEMNO', 'CODE', 'NUMBER', 'OEM', 'OENUMBER',
  // бренд / производитель
  'БРЕНД', 'BRAND', 'ПРОИЗВОДИТЕЛЬ', 'ВИРОБНИК', 'ФИРМА', 'ФРМА', 'МАРКА', 'MANUFACTURER', 'MAKER',
  // название
  'НАИМЕНОВАНИЕ', 'НАЙМЕНУВАННЯ', 'НАЗВАНИЕ', 'НАЗВА', 'НОМЕНКЛАТУРА', 'ОПИСАНИЕ', 'ОПИС', 'ТОВАР',
  'NAME', 'DESCRIPTION', 'PRODUCT', 'ITEM',
  // цена / количество / наличие / фото
  'ЦЕНА', 'ЦНА', 'PRICE', 'КОЛВО', 'КОЛИЧЕСТВО', 'КЛЬКСТЬ', 'QTY', 'QUANTITY', 'ОСТАТОК', 'ЗАЛИШОК',
  'НАЛИЧИЕ', 'НАЯВНСТЬ', 'STOCK', 'ФОТО', 'PHOTO', 'IMAGE',
]);

// article — уже очищенный артикул (cleanArticle)
export function isHeaderArticle(article: string): boolean {
  return HEADER_ARTICLE_KEYS.has(article);
}
