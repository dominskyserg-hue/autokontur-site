// ============================================================
// КАТЕГОРИЯ "ПО ДВОЙНИКУ" — проверка, что это та же деталь
// ============================================================
// Товар без категории ("A1/САЛЬНИК") берёт категорию у товара с тем же
// брендом и артикулом у другого поставщика (lib/categoryAssignment.ts,
// шаг 3б). Но один артикул иногда стоит у разных деталей ("Пыльник
// рулевой рейки" и "Втулка стабилизатора"). Поэтому двойник принимается,
// только если (решение владельца, "строгий вариант"):
//   - первое слово (тип детали) товара и двойника совпадает — с учётом
//     русских/украинских вариантов и синонимов (SAME_TYPE);
//   - или собственное название ничего не говорит: пустое, только код,
//     общее слово ("W4/ХОДОВАЯ", "Комплект");
//   - или начало первого слова товара есть в названии двойника.
// Сравниваются name_search (нижний регистр, латиница-двойники заменены).
// ============================================================

// Группы слов одного типа детали (начала слов)
const SAME_TYPE: string[][] = [
  ['подшип', 'підшип', 'радіал', 'упорн', 'ступиц', 'маточ'], ['компрес', 'колес'], ['сопло', 'геомет'], ['шарн', 'шрус', 'шркш'],
  ['сальн', 'маслок', 'маслос', 'манже', 'ущіль', 'уплот', 'кольц', 'кільц', 'шайб', 'прокл', 'герметик'],
  ['рычаг', 'ричаг', 'важіл', 'важел', 'тяга', 'тяжк', 'тяги'], ['втулк', 'резинк', 'подушк', 'сайлент', 'с/бл'],
  ['натяж', 'натяг', 'ролик', 'гидронат', 'направл', 'успоко', 'заспок', 'цепь', 'цепи', 'ланцю'], ['ремен', 'ремін', 'ремня', 'пас'], ['шкив', 'шків'],
  ['масл', 'олив', 'олія', 'олій'], ['амор', 'ам', 'тор', 'стійк', 'стойк'], ['датчи', 'давач', 'сенсо'], ['выклю', 'вимик', 'включ', 'перем'],
  ['крышк', 'кришк'], ['клапа'], ['болт', 'гвинт', 'винт'], ['гайк'], ['фильт', 'фільт'], ['опор', 'опорн'], ['пыльн', 'пильн', 'пильо', 'чехол', 'чохол'],
  ['мотор', 'насос', 'електродв', 'электродв'], ['випрям', 'діодн', 'диодн'], ['кріпл', 'кронш', 'крепл'], ['щетк', 'щітк', 'стеклоочист', 'склоочис'],
  ['провод', 'провід', 'дріт', 'свечн', 'свічн'], ['колод'],
];

// Общие слова: такое название не говорит, что это за деталь
const GENERIC_WORDS = ['ходова', 'акция', 'акція', 'комплект', 'набір', 'набор', 'запчаст', 'деталь', 'елемент', 'элемент', 'ремк', 'ремкомплект'];

// Первое слово названия (без служебного префикса поставщика "A1/")
export function firstPartWord(nameSearch: string | null | undefined): string {
  return (nameSearch ?? '').replace(/^\s*(?:[a-zа-яіїєґ]?\d+\/)*\s*/, '').split(/[^a-zа-яіїєґё]+/).find((w) => w.length >= 3) ?? '';
}

function typeGroup(word: string): string {
  const index = SAME_TYPE.findIndex((group) => group.some((start) => word.startsWith(start)));
  return index === -1 ? word.slice(0, 4) : `g${index}`;
}

// true — двойник описывает ту же деталь (или своё название ничего не говорит)
export function twinIsSamePart(ownNameSearch: string | null | undefined, twinNameSearch: string | null | undefined): boolean {
  const own = firstPartWord(ownNameSearch);
  const twin = firstPartWord(twinNameSearch);
  if (!own || !twin) return true;
  if (GENERIC_WORDS.some((word) => own.startsWith(word))) return true;
  if (typeGroup(own) === typeGroup(twin)) return true;
  return (twinNameSearch ?? '').includes(own.slice(0, 5));
}
