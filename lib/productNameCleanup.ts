// ============================================================
// Очищення "сирого" products.name ПРИ ВИВОДІ на сторінку — сам рядок
// у базі НІКОЛИ не змінюється (лишається точно таким, яким прийшов
// із прайсу постачальника). Ця функція викликається лише там, де
// сирий name перетворюється на видиме покупцю ім'я товару
// (lib/productDetail.ts, buildSeoProductName) — тому "очищена назва"
// це не окреме поле в базі, а результат виклику функції "на льоту".
//
// КРОК 1 задачі "очистка назв товарів" (механічне форматування, без
// перекладу мови):
//   1. Службовий префікс постачальника AVDOC на самому початку рядка
//      (код секції прайс-листа, напр. "A1/", "K1/", або кілька
//      альтернативних SKU через слеш без букви — "213935/103924/216689 ")
//   2. Скорочення постачальника "К-Т"/"РЕМК-Т" на початку залишку —
//      розгортаються у повні слова
//   3. Маркетингове "Акция"/"АКЦИЯ" на самому початку — прибирається
//      повністю (це позначка постачальника, не частина назви деталі)
//   4. Суцільний КАПС окремих кириличних слів — приводиться до
//      звичайного вигляду; перша літера ЦІЛОГО рядка лишається
//      великою. Абревіатури з PRESERVED_ABBREVIATIONS (реальні,
//      усталені скорочення на кшталт "ГРМ", "КПП") капс не втрачають.
//      Латиниця, цифри та комбінації літер+цифр (VW, ABS, 1.6, K13)
//      НЕ чіпаються взагалі — курс над ними не проводиться
//
// КРОК 2 (переклад російських слів на українську) — окрема, ще НЕ
// застосована частина тієї ж задачі, буде додана згодом поверх цієї
// функції, коли словник підтверджено
// ============================================================

// Префікс-код секції прайс-листа AVDOC — буква (необов'язково) +
// цифри + слеш, можливо кілька повторів підряд (кілька альтернативних
// SKU у одного товару, напр. масла з декількома номерами постачання —
// "213935/103924/216689 Олива..."). Останній номер у такому ланцюжку
// може бути БЕЗ завершального слеша (просто пробіл далі) — тому
// повторювана група ловить усі "слеш-термінові" сегменти, а
// необов'язкова хвостова група — останній, без слеша
const PRICE_LIST_PREFIX_RE = /^([A-ZА-ЯҐЄІЇ]?\d+\/)+([A-ZА-ЯҐЄІЇ]?\d+)?\s*/i;

// Довший варіант ("РЕМК-Т") ОБОВ'ЯЗКОВО перевіряємо ПЕРШИМ — інакше
// його б зловив коротший патерн "К-Т" як підрядок і лишив зайве "РЕМ".
// (?=\s|$) замість \b — \b орієнтується на \w (лише ASCII-літери), і
// між кириличною "Т" та пробілом межі слова НЕ бачить взагалі
const ABBREVIATIONS: ReadonlyArray<[RegExp, string]> = [
  [/^РЕМК-Т(?=\s|$)\.?\s*/i, 'Ремкомплект '],
  [/^К-Т(?=\s|$)\.?\s*/i, 'Комплект '],
];

// "Акция"/"АКЦИЯ" на самому початку рядка — завжди перше слово,
// перевірено прямим запитом до бойової бази (усі 1666 випадків саме
// такі, жодного варіанту "десь всередині назви")
const AKCIYA_RE = /^акция\s+/i;

// Пунктуація, яка може лишитись одразу на початку рядка після
// видалення префікса/"Акция" (кома, тире тощо)
const LEADING_PUNCTUATION_RE = /^[\s,;:.\-–—]+/;

// Реальні, усталені абревіатури автозапчастинної термінології — НЕ
// "крик" постачальника, а звичний спосіб писати ці терміни. Список
// підібраний за прямим запитом до бойової бази (найчастіші кириличні
// абревіатури в products.name)
const PRESERVED_ABBREVIATIONS: ReadonlySet<string> = new Set([
  'ГБЦ', 'ГРМ', 'КПП', 'АКПП', 'ШРУС', 'ШРКШ', 'ДВЗ', 'ГПК', 'ЕПК', 'СТО',
]);

// Кирилична "слово"-послідовність (укр+рос літери разом, як і в
// lib/carModelTranslation.ts) — латиниця/цифри в неї не потрапляють
const CYRILLIC_WORD_RE = /[а-яёіїєґ]+/gi;

// offset === 0 — це справді ПЕРШИЙ символ усього рядка (а не просто
// перше кириличне слово, яке могло б трапитись і не на початку, якщо
// рядок починається з латиниці/цифр) — лише тоді примусово робимо
// першу літеру великою
function normalizeShouting(text: string): string {
  return text.replace(CYRILLIC_WORD_RE, (word, offset: number) => {
    const isShouting = word.length >= 2 && word === word.toUpperCase();
    const shouldPreserve = PRESERVED_ABBREVIATIONS.has(word.toUpperCase());
    let result = isShouting && !shouldPreserve ? word.toLowerCase() : word;
    if (offset === 0) {
      result = result.charAt(0).toUpperCase() + result.slice(1);
    }
    return result;
  });
}

/**
 * Очищена назва товару для показу покупцю — БЕЗ зміни мови (переклад
 * російських слів — окремий, ще не застосований крок). null, якщо
 * після очищення нічого не лишилось (порожній рядок).
 */
export function buildCleanProductName(rawName: string | null | undefined): string | null {
  const trimmed = (rawName ?? '').trim();
  if (!trimmed) return null;

  let result = trimmed.replace(PRICE_LIST_PREFIX_RE, '');
  for (const [pattern, replacement] of ABBREVIATIONS) {
    result = result.replace(pattern, replacement);
  }
  result = result.replace(AKCIYA_RE, '').replace(LEADING_PUNCTUATION_RE, '');
  result = normalizeShouting(result).trim();

  return result || null;
}
